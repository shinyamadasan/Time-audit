// Refined A only: isolated browser design checks, not production persistence/regression tests.
import { chromium, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const dir = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(dir, '../../playwright-report/task-018-refined-a');
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
const results = [];
let assertions = 0;
function check(value, message) { assertions++; if (!value) throw Error(message); }
const snapshot = page => page.evaluate(() => refinedASnapshot());
const settled = page => page.waitForFunction(() => !refinedASnapshot().pending && refinedASnapshot().activeIds.length === 21);
try {
  for (const [width, height, view] of [[390, 844, 'mobile'], [1440, 900, 'desktop']]) {
    const page = await browser.newPage({ viewport: { width, height }, deviceScaleFactor: 1 });
    const errors = [], requests = [];
    page.on('pageerror', error => errors.push(error.message)); page.on('request', request => requests.push(request.url()));
    await page.addInitScript(() => { Storage.prototype.setItem = () => { throw Error('Mock must not persist'); }; });
    await page.goto(pathToFileURL(path.join(dir, 'A-refined.html')).href);
    const preview = page.getByRole('region', { name: 'Unfinished preview', exact: true });
    await preview.locator('.task-row').first().waitFor();
    const original = (await snapshot(page)).source;
    const dimensions = await preview.evaluate(panel => ({ height: panel.getBoundingClientRect().height, rows: [...panel.querySelectorAll('.task-row')].map(row => row.getBoundingClientRect().height), targets: [...panel.querySelectorAll('.complete-target,.title-button,.more-button')].map(target => ({ width: target.getBoundingClientRect().width, height: target.getBoundingClientRect().height })) }));
    check(dimensions.rows.length === 5, 'Exactly five preview rows');
    check(dimensions.targets.every(t => t.width >= 44 && t.height >= 44), '44px touch targets');
    check(await preview.getByRole('searchbox').count() === 0, 'No permanent preview search');
    check(await preview.locator('[data-action=next],[data-action=previous]').count() === 0, 'No preview pagination');
    await page.evaluate(() => { scrollTo(0, 0); document.body.classList.add('document-capture'); });
    await page.screenshot({ path: path.join(out, `${view}-my-day-full.png`), fullPage: true });
    await preview.screenshot({ path: path.join(out, `${view}-five-task-preview.png`) });
    await page.evaluate(() => document.body.classList.remove('document-capture'));
    await page.evaluate(() => scrollTo(0, Math.max(0, document.querySelector('.preview-shell').getBoundingClientRect().top + scrollY - 110)));
    await page.screenshot({ path: path.join(out, `${view}-my-day-preview.png`) });
    await preview.locator('.more-button').first().click();
    const menuBox = await page.getByRole('menu').boundingBox();
    check(menuBox.x >= 0 && menuBox.x + menuBox.width <= width && menuBox.y >= 0 && menuBox.y + menuBox.height <= height, 'Menu stays in viewport');
    check((await preview.boundingBox()).height === dimensions.height, 'Menu overlays without expanding section');
    await page.screenshot({ path: path.join(out, `${view}-more-menu.png`) });
    await page.keyboard.press('ArrowDown');
    check(await page.evaluate(() => document.activeElement.textContent.includes('Move to today')), 'Menu keyboard arrows');
    await page.keyboard.press('Escape');
    check(await page.getByRole('menu').count() === 0, 'Escape closes menu');
    await preview.locator('.more-button').first().click();
    await page.getByRole('menuitem', { name: 'Done earlier…', exact: true }).click();
    check(await page.locator('#reported-date').inputValue() === '2026-10-15', 'Date defaults today');
    await page.locator('#reported-date').fill('2026-10-16');
    await page.getByRole('button', { name: 'Save completion', exact: true }).click();
    check((await snapshot(page)).activeIds.length === 22 && await page.getByRole('dialog', { name: 'Done earlier', exact: true }).isVisible(), 'Future actual date rejected');
    await page.getByRole('button', { name: 'Yesterday', exact: true }).click();
    await page.screenshot({ path: path.join(out, `${view}-done-earlier.png`) });
    await page.getByRole('button', { name: 'Save completion', exact: true }).click();
    await settled(page);
    check((await snapshot(page)).outcomes[0][1].date === '2026-10-14', 'Actual reported date preserved');
    check((await preview.boundingBox()).height <= dimensions.height, 'No success-banner layout expansion');
    const noticeBox = await page.locator('.undo-notice').boundingBox();
    check(noticeBox.height <= 48 && noticeBox.width < width - 32, 'Compact Undo notice');
    await page.screenshot({ path: path.join(out, `${view}-temporary-undo.png`) });
    await page.getByRole('button', { name: 'Undo', exact: true }).click();
    check((await snapshot(page)).activeIds.length === 22, 'Undo restores exact entry');
    await preview.getByRole('button', { name: 'View all', exact: false }).click();
    const backlog = page.getByRole('dialog', { name: 'All unfinished tasks', exact: true });
    await expect(backlog).toBeVisible();
    check(await backlog.locator('.task-row').count() === 22, 'All 22 tasks in backlog');
    check(await backlog.getByRole('searchbox').evaluate(input => document.activeElement === input), 'Search focused by View all');
    const backlogBox = await backlog.boundingBox();
    check(backlogBox.x >= 0 && backlogBox.x + backlogBox.width <= width && backlogBox.y >= 0 && backlogBox.y + backlogBox.height <= height, 'Bounded full backlog');
    check(await backlog.locator('.backlog-rows').evaluate(list => list.scrollHeight > list.clientHeight), 'Backlog scrolls inside window');
    check((await preview.boundingBox()).height === dimensions.height, 'Opening backlog preserves preview footprint');
    await page.screenshot({ path: path.join(out, `${view}-full-backlog.png`) });
    const long = backlog.locator('.title-button').filter({ hasText: 'onboarding research' });
    await long.click();
    check(await long.getAttribute('aria-expanded') === 'true', 'Long titles expand in place');
    await page.screenshot({ path: path.join(out, `${view}-backlog-long-title.png`) });
    await backlog.getByRole('searchbox').fill('volunteer');
    check(await backlog.locator('.task-row').count() === 1 && await backlog.locator('.task-title').textContent() === 'Check the volunteer roster', 'Search reaches tasks beyond preview');
    await page.screenshot({ path: path.join(out, `${view}-backlog-search.png`) });
    await backlog.locator('.more-button').click();
    await page.screenshot({ path: path.join(out, `${view}-backlog-menu.png`) });
    await page.getByRole('menuitem', { name: 'Done earlier…', exact: true }).click();
    await page.getByRole('button', { name: 'Yesterday', exact: true }).click();
    await page.screenshot({ path: path.join(out, `${view}-backlog-date.png`) });
    await page.keyboard.press('Escape');
    check(await backlog.isVisible() && await page.locator('#reported-date').count() === 0, 'Escape closes nested date only');
    await backlog.locator('[data-complete]').check();
    await settled(page);
    check((await snapshot(page)).outcomes[0][0] === 19 && (await snapshot(page)).outcomes[0][1].date === '2026-10-15', 'One check completes correct searched task today');
    await page.getByRole('button', { name: 'Undo', exact: true }).click();
    check((await snapshot(page)).activeIds.length === 22 && await backlog.locator('.task-row').count() === 1, 'Undo restores searched task without losing query');
    await backlog.getByRole('searchbox').fill('no such task');
    await expect(backlog.getByRole('heading', { name: 'No matching tasks', exact: true })).toBeVisible();
    await page.screenshot({ path: path.join(out, `${view}-backlog-no-matches.png`) });
    await page.keyboard.press('Escape');
    check(!await backlog.isVisible(), 'Escape closes backlog');
    check(await preview.getByRole('button', { name: 'View all', exact: false }).evaluate(button => button === document.activeElement), 'Focus returns to View all');
    await page.getByRole('button', { name: 'Fail next action: off', exact: true }).click();
    await preview.locator('[data-complete]').first().check();
    await expect(page.getByRole('button', { name: 'Retry', exact: true })).toBeVisible();
    check((await snapshot(page)).activeIds.length === 22, 'Failed mock retains task');
    await page.screenshot({ path: path.join(out, `${view}-save-error.png`) });
    await page.getByRole('button', { name: 'Retry', exact: true }).click();
    await settled(page);
    if (width === 390) {
      await page.getByRole('button', { name: 'Undo', exact: true }).focus();
      await page.waitForTimeout(8200);
      check(await page.locator('.undo-notice').isVisible(), 'Undo expiry pauses while focused');
      await preview.locator('[data-complete]').first().focus(); await page.mouse.move(0, 0);
      await expect(page.locator('.undo-notice')).toBeHidden({ timeout: 9500 });
      check((await snapshot(page)).activeIds.length === 21, 'Expiry hides notice without reverting completion');
    } else await page.getByRole('button', { name: 'Undo', exact: true }).click();
    check(JSON.stringify((await snapshot(page)).source) === JSON.stringify(original), 'Original planned history unchanged');
    check(!await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), 'No horizontal overflow');
    check(errors.length === 0 && requests.every(url => url.startsWith('file:')), 'No exceptions, external requests or persistence');
    results.push({ viewport: { width, height }, previewHeight: dimensions.height, rowHeights: dimensions.rows, fiveRowsHeight: dimensions.rows.reduce((a, b) => a + b, 0), backlog: backlogBox, notice: noticeBox, errors, externalRequests: 0 });
    await page.close();
  }
  await fs.writeFile(path.join(out, 'measurements.json'), JSON.stringify({ assertions, results, scope: 'Mock-only design evidence; not a real completion/synchronization proof' }, null, 2));
  console.log(JSON.stringify({ assertions, results }, null, 2));
} finally { await browser.close(); }
